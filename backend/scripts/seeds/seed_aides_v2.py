"""
Seed the normalised aides_v2 tables in Supabase from the existing aids.py data.

Run:
    cd backend/scripts && python seed_aides_v2.py

Requires SUPABASE_URL and SUPABASE_SECRET_KEY in backend/.env
"""

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from dotenv import load_dotenv

load_dotenv(os.path.join(os.path.dirname(__file__), "..", ".env"))

from aids import AIDES
from supabase import create_client

SUPABASE_URL = os.environ["SUPABASE_URL"]
SUPABASE_KEY = os.environ["SUPABASE_SECRET_KEY"]

supabase = create_client(SUPABASE_URL, SUPABASE_KEY)

# Mapping from JSONB criteres keys to join tables
JOIN_TABLES = {
    "protectionRequise": "aides_protections",
    "proprietaireEligible": "aides_proprietaires",
    "travauxEligibles": "aides_travaux",
    "regionEligible": "aides_regions",
    "departementEligible": "aides_departements",
    "segmentEligible": "aides_segments",
    "etatConservationRequis": "aides_etats_conservation",
}

# Column name for the code in each join table
JOIN_CODE_COLUMNS = {
    "aides_protections": "protection_code",
    "aides_proprietaires": "proprietaire_code",
    "aides_travaux": "travaux_code",
    "aides_regions": "region_code",
    "aides_departements": "departement_code",
    "aides_segments": "segment_code",
    "aides_etats_conservation": "etat_conservation_code",
}


def build_conditions_text(criteres: dict) -> str | None:
    """Convert criteresSupplementaires list[dict] to readable text."""
    supplements = criteres.get("criteresSupplementaires", [])
    if not supplements:
        return None
    lines = []
    for item in supplements:
        label = item.get("label", "")
        desc = item.get("description", "")
        lines.append(f"- {label} : {desc}")
    return "\n".join(lines)


def transform_aide(aide: dict) -> dict:
    """Transform an aide from aids.py format to aides_v2 row (no id — generated by Postgres)."""
    criteres = aide.get("criteres") or {}

    row = {
        "nom": aide["nom"],
        "nom_court": aide["nom_court"],
        "description": aide["description"],
        "description_longue": aide.get("description_longue"),
        "categorie": aide["categorie"],
        "type": aide["type"],
        "organisme": aide["organisme"],
        "montant_max": aide.get("montant_max"),
        "taux_max": aide.get("taux_max"),
        "montant_min": aide.get("montant_min"),
        "plancher": aide.get("plancher"),
        "base_ttc": aide.get("base_ttc", False),
        "commune_max_population": criteres.get("communeMaxPopulation")
        or (10000 if criteres.get("communeDeMoins10000Hab") else None),
        "cofinancement_requis": criteres.get("cofinancementRequis", False),
        "architecte_requis": criteres.get("architecteRequis", False),
        "conditions_eligibilite_detail": build_conditions_text(criteres),
        "demarche_description": aide.get("demarche_description"),
        "documents_requis": aide.get("documents_requis", []),
        "delai_instruction": aide.get("delai_instruction"),
        "date_ouverture": aide.get("date_ouverture"),
        "date_limite": aide.get("date_limite"),
        "permanent": aide.get("permanent", True),
        "url_officielle": aide.get("url_officielle"),
        "formulaire_url": aide.get("formulaire_url"),
        "tags": aide.get("tags", []),
    }
    return row


def extract_join_values(aide: dict) -> dict[str, list[str]]:
    """Extract join table values from an aide's criteres."""
    criteres = aide.get("criteres") or {}
    result = {}

    for critere_key, table_name in JOIN_TABLES.items():
        values = criteres.get(critere_key, [])
        if not values:
            continue
        if not isinstance(values, list):
            values = [values]
        result[table_name] = [str(v) for v in values]

    return result


def main():
    print(f"Seeding {len(AIDES)} aides into aides_v2 + join tables...\n")

    for aide in AIDES:
        old_id = aide["id"]
        row = transform_aide(aide)

        # Insert aide and get back the generated UUID
        # Use nom_court as dedup key (unique per aide in our dataset)
        result = supabase.table("aides_v2").insert(row).execute()
        uuid = result.data[0]["id"]
        print(f"  ✓ {old_id} → {uuid} — {aide['nom_court']}")

        # Insert join table rows using the new UUID
        joins = extract_join_values(aide)
        for table_name, values in joins.items():
            code_col = JOIN_CODE_COLUMNS[table_name]
            rows = [{"aide_id": uuid, code_col: v} for v in values]
            supabase.table(table_name).insert(rows).execute()

    print(f"\nDone! {len(AIDES)} aides + jointures insérées.")


if __name__ == "__main__":
    main()
